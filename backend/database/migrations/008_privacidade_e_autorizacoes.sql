CREATE TABLE aceites_privacidade (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contato_id BIGINT NOT NULL,
  aceito BOOLEAN NOT NULL,
  texto_apresentado TEXT NOT NULL,
  versao_texto VARCHAR(100) NOT NULL,
  origem_id BIGINT NOT NULL,
  canal VARCHAR(50) NOT NULL,
  registrado_por_usuario_id BIGINT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT aceites_privacidade_contato_id_fkey
    FOREIGN KEY (contato_id)
    REFERENCES contatos(id),
  CONSTRAINT aceites_privacidade_origem_id_fkey
    FOREIGN KEY (origem_id)
    REFERENCES origens(id),
  CONSTRAINT aceites_privacidade_usuario_id_fkey
    FOREIGN KEY (registrado_por_usuario_id)
    REFERENCES usuarios(id)
    ON DELETE SET NULL,
  CONSTRAINT aceites_privacidade_aceite_obrigatorio CHECK (aceito = TRUE),
  CONSTRAINT aceites_privacidade_texto_nao_vazio CHECK (
    LENGTH(TRIM(texto_apresentado)) >= 10
  ),
  CONSTRAINT aceites_privacidade_canal_valido CHECK (
    canal IN ('formulario_publico', 'cadastro_manual', 'outro')
  )
);

CREATE UNIQUE INDEX aceites_privacidade_resposta_identica_unica
  ON aceites_privacidade (
    contato_id,
    versao_texto,
    origem_id,
    canal,
    MD5(texto_apresentado)
  )
  WHERE aceito = TRUE;

CREATE INDEX aceites_privacidade_contato_id_indice
  ON aceites_privacidade (contato_id);

CREATE INDEX aceites_privacidade_criado_em_indice
  ON aceites_privacidade (criado_em DESC);

