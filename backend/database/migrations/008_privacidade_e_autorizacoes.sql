CREATE TABLE textos_formulario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo VARCHAR(50) NOT NULL,
  versao VARCHAR(100) NOT NULL,
  texto TEXT NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT textos_formulario_tipo_valido CHECK (
    tipo IN ('aviso_privacidade', 'mensagens', 'ligacoes')
  ),
  CONSTRAINT textos_formulario_versao_nao_vazia CHECK (
    LENGTH(TRIM(versao)) >= 2
  ),
  CONSTRAINT textos_formulario_texto_nao_vazio CHECK (
    LENGTH(TRIM(texto)) >= 10
  ),
  CONSTRAINT textos_formulario_tipo_versao_unicos UNIQUE (tipo, versao)
);

CREATE UNIQUE INDEX textos_formulario_tipo_ativo_unico
  ON textos_formulario (tipo)
  WHERE ativo = TRUE;

CREATE TRIGGER textos_formulario_atualizar_data
BEFORE UPDATE ON textos_formulario
FOR EACH ROW
EXECUTE FUNCTION atualizar_data_modificacao();

